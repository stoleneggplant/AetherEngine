    // MARK: - Mapping

    @Test("L1 maps onto the reference model's metadata", arguments: golden)
    func mapsLevel1(_ golden: GoldenCase) {
        let metadata = Mapping.metadata(for: golden.level1)
        #expect(metadata.maxSCL.count == 3)
        for component in metadata.maxSCL { #expect(Self.close(component, golden.maxSCL)) }
        #expect(Self.close(metadata.averageMaxRGB, golden.averageMaxRGB))
        #expect(metadata.distribution.map(\.percentage) == Mapping.percentages)
        for (got, want) in zip(metadata.distribution.map(\.percentile), golden.percentiles) {
            #expect(Self.close(got, want), "\(golden.name): \(got) vs \(want)")
        }
    }

    @Test("ST 2094-40 payload and prefix SEI bytes are exact", arguments: golden)
    func serialises(_ golden: GoldenCase) {
        let payload = Mapping.t35Payload(golden.expectedMetadata)
        #expect(Self.hex(payload) == golden.payloadHex)
        #expect(Self.hex(Mapping.hevcPrefixSEINAL(t35Payload: payload)) == golden.seiHex)
    }

    @Test("The CDF entries never decrease and stop at the peak")
    func distributionIsMonotone() {
        for maxPQ in stride(from: 2081, through: 4095, by: 101) {
            for avgPQ in stride(from: 819, to: maxPQ, by: 97) {
                let m = Mapping.metadata(for: .init(minPQ: 0, maxPQ: maxPQ, avgPQ: avgPQ))
                // The 5% and 10% slots are the application-version-1 extras, not CDF points.
                let cdf = m.distribution.filter { $0.percentage != 5 && $0.percentage != 10 }.map(\.percentile)
                #expect(cdf == cdf.sorted())
                #expect(cdf.last == m.maxSCL[0])
                #expect(m.averageMaxRGB <= m.maxSCL[0])
            }
        }
    }

    @Test("PQ conversions invert each other")
    func pqRoundTrip() {
        for nits in [0.005, 0.1, 1, 48, 100, 203, 1000, 4000, 10000] {
            let back = Mapping.pqToNits(Mapping.nitsToPQ(nits))
            #expect(abs(back - nits) <= max(nits * 1e-9, 1e-9))
        }
        // 3079 is the 12-bit PQ code of 1000 cd/m2, which is what dovi_tool writes for a 1000-nit peak.
        #expect(abs(Mapping.pqToNits(3079) - 1000) < 1)
    }

    @Test("SEI escapes emulation-prone payload bytes")
    func escapesEmulation() {
        let nal = Mapping.hevcPrefixSEINAL(t35Payload: [0x00, 0x00, 0x01, 0x00, 0x00, 0x00])
        #expect(nal == [0x4E, 0x01, 0x04, 0x06, 0x00, 0x00, 0x03, 0x01, 0x00, 0x00, 0x03, 0x00, 0x80])
    }

