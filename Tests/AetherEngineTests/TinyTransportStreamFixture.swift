///       -profile:v baseline -crf 51 -g 2 -keyint_min 2 -sc_threshold 0 \
///       -x264-params "bframes=0:repeat-headers=1" -pix_fmt yuv420p -f mpegts \
///       -mpegts_service_type digital_tv -pat_period 60 -sdt_period 60 tiny-live.ts
enum TinyTransportStreamFixture {

    /// Video keyframes in the stream, one per second.
    static let keyframeCount = 8

    static var data: Data { Data(base64Encoded: base64.joined())! }

    /// The stream as a live source serves it: from byte 0 to its end, then EOF, with no length and
    /// no disc probe (a disc probe reads ahead, and a live open does not rewind after it).
    final class LiveReader: IOReader, @unchecked Sendable {
        private let bytes: Data
        init(bytes: Data = TinyTransportStreamFixture.data) { self.bytes = bytes }
        private let lock = NSLock()
        private var position = 0

        func read(_ buffer: UnsafeMutablePointer<UInt8>?, size: Int32) -> Int32 {
            guard let buffer, size > 0 else { return -1 }
            return lock.withLock {
                let n = min(Int(size), bytes.count - position)
                guard n > 0 else { return 0 }
                bytes.withUnsafeBytes { raw in
                    _ = memcpy(buffer, raw.baseAddress! + position, n)
                }
                position += n
                return Int32(n)
            }
        }

        func seek(offset: Int64, whence: Int32) -> Int64 {
            lock.withLock {
                switch whence {
                case SEEK_SET where offset >= 0 && offset <= Int64(bytes.count):
                    position = Int(offset)
                case SEEK_CUR where offset == 0:
                    break
                default:
                    return -1
                }
                return Int64(position)
            }
        }

        func close() {}
        var discImageProbeEnabled: Bool { false }
    }

